-- 1. Enable PostGIS extension in the extensions schema
create extension if not exists postgis with schema extensions;

-- 2. Wards (Simulated mock data for demo / competition)
-- SIMULATED DATA: Ward boundaries, names, and populations are mock values for demonstration.
create table if not exists public.wards (
  id int generated by default as identity primary key,
  name text not null,
  population int not null,
  density_score int not null check (density_score between 0 and 4),
  centre extensions.geography(Point, 4326),
  is_simulated boolean not null default true
);

-- 3. Departments
create table if not exists public.departments (
  id int generated by default as identity primary key,
  name text not null unique
);

-- 4. User Profiles (Extends auth.users)
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  role text not null check (role in ('citizen', 'officer', 'admin')) default 'citizen',
  department_id int references public.departments(id) on delete set null,
  ward_id int references public.wards(id) on delete set null
);

-- 5. Categories
create table if not exists public.categories (
  key text primary key,
  label text not null,
  base_weight numeric not null check (base_weight between 0 and 1),
  sla_hours int not null check (sla_hours > 0),
  max_weather_boost int not null check (max_weather_boost between 0 and 15)
);

-- 6. Issues (Core problem entities)
create table if not exists public.issues (
  id uuid primary key default gen_random_uuid(),
  category text not null references public.categories(key),
  severity_level text not null check (severity_level in ('minor', 'moderate', 'dangerous')) default 'moderate',
  description text,
  location extensions.geography(Point, 4326) not null,
  address text,
  ward_id int references public.wards(id) on delete set null,
  department_id int references public.departments(id) on delete set null,
  road_class text not null check (road_class in ('main', 'secondary', 'local')) default 'local',
  status text not null check (status in ('reported', 'verified', 'assigned', 'in_progress', 'resolved', 'reopened')) default 'reported',
  assigned_to uuid references public.profiles(id) on delete set null,
  unique_reporters int not null default 1,
  reopen_count int not null default 0,
  priority_score int not null default 0,
  priority_band text check (priority_band in ('High', 'Medium', 'Low')),
  score_breakdown jsonb,
  reasons_text text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz
);

-- 7. Individual Citizen Reports
create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  issue_id uuid not null references public.issues(id) on delete cascade,
  user_id uuid references auth.users(id) on delete set null,
  is_anonymous boolean not null default false,
  on_behalf boolean not null default false,
  description text,
  photo_url text,
  photo_location extensions.geography(Point, 4326),
  report_location extensions.geography(Point, 4326),
  ai_suggested_category text,
  ai_suggested_severity text,
  created_at timestamptz not null default now()
);

-- 8. Upvotes ("I am affected too")
create table if not exists public.upvotes (
  issue_id uuid not null references public.issues(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (issue_id, user_id)
);

-- 9. Status History (Audit timeline)
create table if not exists public.status_history (
  id uuid primary key default gen_random_uuid(),
  issue_id uuid not null references public.issues(id) on delete cascade,
  status text not null check (status in ('reported', 'verified', 'assigned', 'in_progress', 'resolved', 'reopened')),
  changed_by uuid references auth.users(id) on delete set null,
  note text,
  created_at timestamptz not null default now()
);

-- 10. Resolutions (Officer proof of work)
create table if not exists public.resolutions (
  id uuid primary key default gen_random_uuid(),
  issue_id uuid not null references public.issues(id) on delete cascade,
  officer_id uuid references auth.users(id) on delete set null,
  after_photo_url text,
  after_photo_location extensions.geography(Point, 4326),
  distance_from_issue_m numeric,
  created_at timestamptz not null default now()
);

-- 11. Fix Confirmations (Citizen verification votes)
create table if not exists public.fix_confirmations (
  issue_id uuid not null references public.issues(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  is_fixed boolean not null,
  created_at timestamptz not null default now(),
  primary key (issue_id, user_id)
);

-- 12. Sensitive Places (Exposure multipliers)
create table if not exists public.places (
  id uuid primary key default gen_random_uuid(),
  kind text not null check (kind in ('school', 'hospital', 'bus_stop', 'market')),
  name text not null,
  location extensions.geography(Point, 4326) not null
);

-- 13. Weather Cache
create table if not exists public.weather_cache (
  ward_id int primary key references public.wards(id) on delete cascade,
  rain_intensity numeric not null check (rain_intensity between 0 and 1) default 0,
  fetched_at timestamptz not null default now()
);

-- 14. Application Settings (Global config flags)
create table if not exists public.app_settings (
  key text primary key,
  value text not null
);

-- Spatial Indexes
create index if not exists idx_issues_location on public.issues using gist (location);
create index if not exists idx_places_location on public.places using gist (location);
create index if not exists idx_reports_issue_id on public.reports(issue_id);
create index if not exists idx_upvotes_issue_id on public.upvotes(issue_id);
create index if not exists idx_status_history_issue_id on public.status_history(issue_id);

